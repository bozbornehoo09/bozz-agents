#!/usr/bin/env python3
"""Keep the decisions index and the decisions-in-force map consistent with the ADRs.

The ADR body's ``**Status:**`` line is the source of truth; the index
(``README.md`` in the decisions directory) mirrors it, and the hand-kept map
(``IN-FORCE.md``, see ../references/template-in-force.md) cites the ADRs in
force. ``check`` and ``lines`` never write; ``write`` is the only command that
does, and it touches just two things.

  check [--dir docs/decisions] [--index README.md] [--map IN-FORCE.md] [--json]
  lines [--dir docs/decisions]    print the canonical list-form index lines
  write [--dir docs/decisions] [--index README.md] [--map IN-FORCE.md]
        [--project NAME] [--date YYYY-MM-DD] [--dry-run]
        regenerate the index lines between the adr-index markers in the index
        (creating the index when it is missing, appending the block when the
        file names no ADR yet) and create the map from its skeleton when the
        map is missing. An existing map is never written; an index without
        markers that names any ADR (ADR-NNNN, or an ADR's file name, in any
        layout) is never written either.

Finding lines: ``FIX <class> <file>:<line> <detail>``. Classes:
  missing-status       ADR body has no **Status:** line
  bad-status           Status is not Accepted | Proposed | Deprecated |
                       Superseded by ADR-NNNN
  status-mismatch      index status differs from the body status
  missing-from-index   an ADR file has no index entry
  index-orphan         an index entry names a file that does not exist
  duplicate-number     two ADR files share a number
  broken-supersedence  "Superseded by ADR-X" without X existing or without
                       X carrying "**Supersedes:** ADR-<this>"
Map classes, reported only when the map file exists:
  map-missing          an Accepted ADR the map never cites
  map-orphan           the map cites an ADR number with no file
  superseded-in-map    an "In force" line cites a Superseded ADR without its
                       successor, or a Deprecated ADR
``write`` prints one line per file: WROTE, CREATED, UNCHANGED, KEEP (an
existing map) or SKIP (an index kept by hand outside the markers), with
WOULD- in front of WROTE and CREATED under --dry-run.
Exit status: 0 after a completed check or write (findings or not), 2 on usage error.
Standard library only.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
from pathlib import Path
import re
import sys


ADR_FILE_RE = re.compile(r"^(?P<num>\d{4})-[a-z0-9][a-z0-9-]*\.md$")
STATUS_RE = re.compile(r"^\*\*Status:\*\*\s*(?P<value>.+?)\s*$")
SUPERSEDES_RE = re.compile(r"^\*\*Supersedes:\*\*\s*(?P<value>.+?)\s*$")
TITLE_RE = re.compile(r"^#\s+(?:ADR-\d{4}:\s*)?(?P<title>.+?)\s*$")
VALID_STATUS_RE = re.compile(r"^(Accepted|Proposed|Deprecated|Superseded by ADR-(?P<by>\d{4}))$")
# Index entries: a list line "- [ADR-NNNN](file.md) — Title — Status" or a
# table row "| [ADR-NNNN](file.md) | Title | Status |".
LIST_ENTRY_RE = re.compile(
    r"^\s*[-*]\s+\[ADR-(?P<num>\d{4})\]\((?P<file>[^)]+)\)\s+—\s+(?P<title>.+?)\s+—\s+(?P<status>.+?)\s*$"
)
TABLE_ENTRY_RE = re.compile(
    r"^\s*\|\s*\[ADR-(?P<num>\d{4})\]\((?P<file>[^)]+)\)\s*\|\s*(?P<title>.+?)\s*\|\s*(?P<status>.+?)\s*\|\s*$"
)
BEGIN_PREFIX = "<!-- adr-index:begin"
BEGIN = "<!-- adr-index:begin (generated by adr_index.py write from each ADR's Status line; edit the ADRs, not these lines) -->"
END = "<!-- adr-index:end -->"
COMMENT_RE = re.compile(r"<!--.*?-->", re.S)
CITE_RE = re.compile(r"ADR-(\d{4})")
TEMPLATE = Path(__file__).resolve().parent.parent / "references" / "template-in-force.md"


def read_adr(path: Path) -> dict:
    lines = path.read_text(encoding="utf-8").splitlines()
    record = {
        "file": path.name,
        "num": ADR_FILE_RE.match(path.name).group("num"),
        "title": None,
        "status": None,
        "status_line": None,
        "supersedes": [],
    }
    for index, line in enumerate(lines[:40], start=1):
        if record["title"] is None:
            title = TITLE_RE.match(line)
            if title:
                record["title"] = title.group("title")
        status = STATUS_RE.match(line)
        if status and record["status"] is None:
            record["status"] = status.group("value")
            record["status_line"] = index
        supersedes = SUPERSEDES_RE.match(line)
        if supersedes:
            record["supersedes"] = re.findall(r"ADR-(\d{4})", supersedes.group("value"))
    return record


def read_index(path: Path) -> list[dict]:
    entries = []
    if not path.exists():
        return entries
    for index, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        match = LIST_ENTRY_RE.match(line) or TABLE_ENTRY_RE.match(line)
        if match:
            entries.append({**match.groupdict(), "line": index})
    return entries


def check(directory: Path, index_name: str, map_name: str = "IN-FORCE.md") -> list[dict]:
    findings: list[dict] = []

    def add(kind: str, file: str, line: int, detail: str) -> None:
        findings.append({"class": kind, "file": file, "line": line, "detail": detail})

    adrs = [read_adr(path) for path in sorted(directory.iterdir()) if ADR_FILE_RE.match(path.name)]
    by_num: dict[str, dict] = {}
    for adr in adrs:
        if adr["num"] in by_num:
            add("duplicate-number", adr["file"], 1, f"ADR-{adr['num']} also used by {by_num[adr['num']]['file']}")
        else:
            by_num[adr["num"]] = adr

    for adr in adrs:
        status = adr["status"]
        if status is None:
            add("missing-status", adr["file"], 1, "no **Status:** line in the first 40 lines")
            continue
        valid = VALID_STATUS_RE.match(status)
        if not valid:
            add("bad-status", adr["file"], adr["status_line"], f"status {status!r} is not a canonical value")
            continue
        successor_num = valid.group("by")
        if successor_num:
            successor = by_num.get(successor_num)
            if successor is None:
                add("broken-supersedence", adr["file"], adr["status_line"], f"ADR-{successor_num} does not exist")
            elif adr["num"] not in successor["supersedes"]:
                add(
                    "broken-supersedence",
                    adr["file"],
                    adr["status_line"],
                    f"{successor['file']} has no '**Supersedes:** ADR-{adr['num']}' line",
                )

    index_path = directory / index_name
    entries = read_index(index_path)
    indexed_files = set()
    for entry in entries:
        indexed_files.add(entry["file"])
        adr = next((item for item in adrs if item["file"] == entry["file"]), None)
        if adr is None:
            add("index-orphan", index_name, entry["line"], f"{entry['file']} does not exist")
            continue
        if adr["status"] is not None and entry["status"] != adr["status"]:
            add(
                "status-mismatch",
                index_name,
                entry["line"],
                f"index says {entry['status']!r}; {adr['file']}:{adr['status_line']} says {adr['status']!r} (body is truth)",
            )
    for adr in adrs:
        if adr["file"] not in indexed_files:
            add("missing-from-index", adr["file"], 1, f"ADR-{adr['num']} has no entry in {index_name}")
    map_path = directory / map_name
    if map_path.is_file():
        findings.extend(check_map(map_path, by_num))
    return findings


def check_map(map_path: Path, by_num: dict[str, dict]) -> list[dict]:
    """Map findings. Comments are blanked but keep their newlines, so line numbers stay true."""
    raw = map_path.read_text(encoding="utf-8")
    text = COMMENT_RE.sub(lambda m: "\n" * m.group(0).count("\n"), raw)
    findings: list[dict] = []
    cited: set[str] = set()
    in_force = False
    for number, line in enumerate(text.splitlines(), start=1):
        if line.startswith("## "):
            in_force = "in force" in line.lower()
        nums = CITE_RE.findall(line)
        cited.update(nums)
        for num in nums:
            adr = by_num.get(num)
            if adr is None:
                findings.append({"class": "map-orphan", "file": map_path.name, "line": number,
                                 "detail": f"ADR-{num} has no file"})
                continue
            status = adr["status"] or ""
            valid = VALID_STATUS_RE.match(status)
            successor = valid.group("by") if valid else None
            if in_force and (status == "Deprecated" or (successor and successor not in nums)):
                findings.append({"class": "superseded-in-map", "file": map_path.name, "line": number,
                                 "detail": f"cites ADR-{num} ({status}) as in force"})
    for num, adr in sorted(by_num.items()):
        if adr["status"] == "Accepted" and num not in cited:
            findings.append({"class": "map-missing", "file": adr["file"], "line": adr["status_line"] or 1,
                             "detail": f"Accepted ADR-{num} is cited nowhere in {map_path.name}"})
    return findings


def canonical_lines(directory: Path) -> list[str]:
    lines = []
    for path in sorted(directory.iterdir()):
        if ADR_FILE_RE.match(path.name):
            adr = read_adr(path)
            lines.append(
                f"- [ADR-{adr['num']}]({adr['file']}) — {adr['title'] or adr['file']} — {adr['status'] or 'MISSING STATUS'}"
            )
    return lines


def table_lines(directory: Path) -> list[str]:
    rows = ["| ADR | Title | Status |", "|---|---|---|"]
    for path in sorted(directory.iterdir()):
        if ADR_FILE_RE.match(path.name):
            adr = read_adr(path)
            title = (adr["title"] or adr["file"]).replace("|", "\\|")
            rows.append(f"| [ADR-{adr['num']}]({adr['file']}) | {title} | {adr['status'] or 'MISSING STATUS'} |")
    return rows


def new_index_text(directory: Path, block: str) -> str:
    return (
        "# Architecture Decision Records\n\n"
        "Each ADR records why a binding decision was made. ADRs are immutable: a change of\n"
        "course is a new ADR that supersedes the old one. The decisions currently in force\n"
        "are mapped in IN-FORCE.md.\n\n" + block + "\n"
    )


def index_update(directory: Path, index_name: str) -> tuple[str, str | None]:
    """(verdict, new text or None). Never rewrites entries that sit outside the markers."""
    path = directory / index_name
    if not path.exists():
        block = "\n".join([BEGIN, *canonical_lines(directory), END])
        return "CREATED", new_index_text(directory, block)
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    begin = next((i for i, l in enumerate(lines) if l.strip().startswith(BEGIN_PREFIX)), None)
    if begin is None:
        # Any mention counts, not only the layouts read_index parses: a hand-kept index in another
        # layout must not get a second, generated list appended to it.
        names = {p.name for p in directory.iterdir() if ADR_FILE_RE.match(p.name)}
        first = next((i for i, l in enumerate(lines, start=1)
                      if re.search(r"ADR-\d{4}", l) or any(name in l for name in names)), None)
        if first is not None:
            return f"SKIP {index_name}:{first} entries are kept by hand outside the adr-index markers; " \
                   f"wrap them in the markers to let write maintain them", None
        block = "\n".join([BEGIN, *canonical_lines(directory), END])
        return "WROTE", text.rstrip("\n") + "\n\n" + block + "\n"
    end = next((i for i in range(begin + 1, len(lines)) if lines[i].strip() == END), None)
    if end is None:
        return f"SKIP {index_name}:{begin + 1} adr-index begin marker has no end marker", None
    inner = lines[begin + 1:end]
    table = any(TABLE_ENTRY_RE.match(l) for l in inner)
    fresh = table_lines(directory) if table else canonical_lines(directory)
    new = "\n".join(lines[: begin + 1] + fresh + lines[end:]) + "\n"
    return ("UNCHANGED" if new == text else "WROTE"), (None if new == text else new)


def skeleton(project: str, date: str) -> str:
    text = TEMPLATE.read_text(encoding="utf-8")
    match = re.search(r"^```markdown\n(.*?)^```", text, re.M | re.S)
    if not match:
        raise ValueError(f"no ```markdown skeleton block in {TEMPLATE}")
    return match.group(1).replace("{project}", project).replace("{date}", date)


def write(directory: Path, index_name: str, map_name: str, project: str, date: str, dry_run: bool) -> list[str]:
    out = []
    verdict, text = index_update(directory, index_name)
    if text is not None and not dry_run:
        (directory / index_name).write_text(text, encoding="utf-8")
    prefix = "WOULD-" if dry_run and verdict in ("WROTE", "CREATED") else ""
    out.append(f"{prefix}{verdict}" + ("" if verdict.startswith("SKIP") else f" {index_name}"))
    map_path = directory / map_name
    if map_path.exists():
        out.append(f"KEEP {map_name} (exists; the map is hand-kept and never overwritten)")
    else:
        body = skeleton(project, date)
        if not dry_run:
            map_path.write_text(body, encoding="utf-8")
        out.append(f"{'WOULD-' if dry_run else ''}CREATED {map_name} (DRAFT skeleton; fill it in by hand)")
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    check_parser = sub.add_parser("check", help="report index/body inconsistencies (read-only)")
    check_parser.add_argument("--dir", default="docs/decisions")
    check_parser.add_argument("--index", default="README.md")
    check_parser.add_argument("--map", default="IN-FORCE.md")
    check_parser.add_argument("--json", action="store_true")
    lines_parser = sub.add_parser("lines", help="print canonical list-form index lines")
    lines_parser.add_argument("--dir", default="docs/decisions")
    write_parser = sub.add_parser("write", help="regenerate the marked index block; create a missing map")
    write_parser.add_argument("--dir", default="docs/decisions")
    write_parser.add_argument("--index", default="README.md")
    write_parser.add_argument("--map", default="IN-FORCE.md")
    write_parser.add_argument("--project", help="name for a new map's title (default: the project folder)")
    write_parser.add_argument("--date", help="YYYY-MM-DD for a new map (default: the system clock)")
    write_parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    directory = Path(args.dir)
    if not directory.is_dir():
        print(f"error: not a directory: {directory}", file=sys.stderr)
        return 2
    if args.command == "lines":
        print("\n".join(canonical_lines(directory)))
        return 0
    if args.command == "write":
        try:
            date = dt.date.fromisoformat(args.date).isoformat() if args.date else dt.date.today().isoformat()
        except ValueError:
            print(f"error: invalid --date {args.date!r}; use YYYY-MM-DD", file=sys.stderr)
            return 2
        resolved = directory.resolve()
        project = args.project or (resolved.parent.parent.name if resolved.parent.name == "docs" else resolved.parent.name)
        try:
            print("\n".join(write(directory, args.index, args.map, project, date, args.dry_run)))
        except (OSError, ValueError) as error:
            print(f"error: {error}", file=sys.stderr)
            return 2
        return 0
    findings = check(directory, args.index, args.map)
    if args.json:
        print(json.dumps({"findings": findings}, sort_keys=True))
    else:
        for item in findings:
            print(f"FIX {item['class']} {item['file']}:{item['line']} {item['detail']}")
        if not findings:
            print("OK no index/body inconsistencies")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
