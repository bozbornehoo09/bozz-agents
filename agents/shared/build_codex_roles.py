#!/usr/bin/env python3
"""Generate Codex custom-agent role files from the canonical agents/*.md.

Codex discovers custom agent roles from `agents/*.toml` under a config folder
(`.codex/agents/` in a project, `~/.codex/agents/` for a user). Each file needs
`name`, `description` and a non-blank `developer_instructions`. This script
writes one such file per subagent role into `codex/agents/`, carrying the
role's Markdown body verbatim as its instructions, so the canonical
`agents/<role>.md` stays the one definition (ADR-0002: generated per-host
output, never a fork).

Only the subagent roles are generated. The session roles (manager, architect,
implementer) are top-level sessions the owner talks to; on Codex they are run
by an explicit prompt (docs/agents.md, "Running on Codex").

Usage:
  python3 -I agents/shared/build_codex_roles.py           # write codex/agents/*.toml
  python3 -I agents/shared/build_codex_roles.py --check   # exit 1 if any file is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
AGENTS = ROOT / "agents"
OUT = ROOT / "codex" / "agents"

SUBAGENT_ROLES = ["review-specialist", "cold-reader", "cold-reader-deep", "artifact-verifier"]
MARKER = "# GENERATED by agents/shared/build_codex_roles.py from agents/{name}.md. Do not edit; regenerate."


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    if not text.startswith("---\n"):
        raise ValueError("missing frontmatter")
    head, _, body = text[4:].partition("\n---\n")
    fields = {}
    for line in head.splitlines():
        key, sep, value = line.partition(":")
        if sep and not line.startswith(" "):
            fields[key.strip()] = value.strip()
    return fields, body.lstrip("\n")


def render(name: str) -> str:
    fields, body = split_frontmatter((AGENTS / f"{name}.md").read_text(encoding="utf-8"))
    if "'''" in body:
        raise ValueError(f"{name}.md body contains ''' and cannot be a TOML literal string")
    tools = {t.strip() for t in fields.get("tools", "").split(",") if t.strip()}
    lines = [
        MARKER.format(name=name),
        f"name = {json.dumps(fields['name'])}",
        f"description = {json.dumps(fields['description'])}",
    ]
    if tools and not tools & {"Write", "Edit", "NotebookEdit"}:
        lines.append('sandbox_mode = "read-only"')
    if name == "cold-reader":
        lines.append("# Set `model` here to a different model from cold-reader-deep's: the gate needs two distinct models.")
    lines.append(f"developer_instructions = '''\n{body.rstrip()}\n'''")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for name in SUBAGENT_ROLES:
        want = render(name)
        path = OUT / f"{name}.toml"
        have = path.read_text(encoding="utf-8") if path.exists() else None
        if have == want:
            continue
        if check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            OUT.mkdir(parents=True, exist_ok=True)
            path.write_text(want, encoding="utf-8")
            print("wrote", path.relative_to(ROOT))
    for s in stale:
        print("STALE", s)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
